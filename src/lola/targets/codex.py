"""Native skill installation for Codex CLI."""

from __future__ import annotations

import os
import shutil
from pathlib import Path

import yaml

import lola.frontmatter as fm
from .base import BaseAssistantTarget, unlink_symlink_if_present


class CodexTarget(BaseAssistantTarget):
    """Install skills using Codex's repository and user discovery paths.

    Commands, agents, MCP configuration, and module instructions are not
    generated by this target.
    """

    name = "codex"
    supports_agents = False

    def get_skill_path(self, project_path: str, scope: str = "project") -> Path:
        """Return the native skill directory for the selected scope."""
        root = Path.home() if scope == "user" else Path(project_path)
        return root / ".agents" / "skills"

    def get_command_path(
        self,
        project_path: str,  # noqa: ARG002
        scope: str = "project",  # noqa: ARG002
    ) -> None:
        """Commands are not supported."""
        return None

    def get_instructions_path(
        self,
        project_path: str,
        scope: str = "project",
    ) -> Path:
        """Resolve the instruction path without generating instructions."""
        if scope == "user":
            root = Path(os.environ.get("CODEX_HOME", Path.home() / ".codex"))
            return root.expanduser() / "AGENTS.md"
        return Path(project_path) / "AGENTS.md"

    def generate_skill(
        self,
        source_path: Path,
        dest_path: Path,
        skill_name: str,
        project_path: str | None = None,  # noqa: ARG002
    ) -> bool:
        """Generate a native skill with its effective installation name."""
        if (
            not skill_name
            or skill_name in {".", ".."}
            or "/" in skill_name
            or "\\" in skill_name
        ):
            return False
        skill_file = source_path / "SKILL.md"
        metadata, body = fm.parse_file(skill_file)
        description = metadata.get("description")
        if not isinstance(description, str) or not description.strip():
            return False

        skill_dest = dest_path / skill_name
        unlink_symlink_if_present(skill_dest)
        if skill_dest.exists():
            shutil.rmtree(skill_dest)
        shutil.copytree(source_path, skill_dest)
        if metadata.get("name") != skill_name:
            metadata["name"] = skill_name
            header = yaml.safe_dump(
                metadata,
                sort_keys=False,
                allow_unicode=True,
            )
            (skill_dest / "SKILL.md").write_text(
                f"---\n{header}---\n\n{body}\n",
            )
        return True

    def generate_command(
        self,
        source_path: Path,  # noqa: ARG002
        dest_dir: Path,  # noqa: ARG002
        cmd_name: str,  # noqa: ARG002
        module_name: str,  # noqa: ARG002
    ) -> bool:
        """Commands are not supported."""
        return False
